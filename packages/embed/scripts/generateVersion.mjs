// Regenerates src/generated/version.ts from the installed @torpor/view's
// package.json, so the compile entry can stamp artifacts in any runtime
// without Node builtins. Run as part of `pnpm build`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const view = JSON.parse(readFileSync(new URL("../../view/package.json", import.meta.url), "utf8"));
const out = `// Generated by scripts/generateVersion.mjs -- do not edit.
// The version of @torpor/view this package was built against. Safe to use
// in any runtime (no Node builtins); the Node-only server entry also
// exposes getRuntimeVersion(), which reads the installed package instead.
export const RUNTIME_VERSION = ${JSON.stringify(view.version)};
`;
mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/generated/version.ts", import.meta.url), out);
console.log(`generated RUNTIME_VERSION = ${view.version}`);
