// Generator for the torpor signal-favoring fixture — 100-component chain,
// stateful counters at C1, C11, ..., C91. Torpor is signal-based: the counter
// lives in a `$watch` object and the value text is a reactive read, so a bump
// re-runs only that node's text effect (no descendant cascade).
//
// Run: `node benchmarks/signal-favoring/torpor-signal-bench/gen.mjs`

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const N = 100;
const STATEFUL_INDICES = [];
for (let i = 1; i <= N; i += 10) STATEFUL_INDICES.push(i);
const isStateful = (i) => i % 10 === 1;

let out = `// Generated by gen.mjs — 100-component chain, stateful counters at C${STATEFUL_INDICES.join(', C')}.\n`;
out += `// Torpor is signal-based: each counter lives in a $watch object and the value text\n`;
out += `// is a reactive read, so a bump re-runs only that node's text effect.\n\n`;

for (const i of STATEFUL_INDICES) {
	out += `let _set${i} = null;\n`;
}
out += '\n';

for (const i of STATEFUL_INDICES) {
	out += `export function bumpAt${i}() { if (_set${i}) _set${i}((v) => v + 1); }\n`;
}
out += '\n';

// Leaf C100
out += `function C100() {\n\t@render {\n\t\t<span class="leaf">100</span>\n\t}\n}\n\n`;

// C99..C1; stateful nodes have a counter
for (let i = N - 1; i >= 1; i--) {
	if (isStateful(i)) {
		out += `function C${i}() {\n`;
		out += `\tlet $state = $watch({ v: 0 });\n`;
		out += `\t_set${i} = (fn) => ($state.v = typeof fn === "function" ? fn($state.v) : fn);\n`;
		out += `\t@render {\n`;
		out += `\t\t<div class="c">\n`;
		out += `\t\t\t${i}:{$state.v}\n`;
		out += `\t\t\t<C${i + 1} />\n`;
		out += `\t\t</div>\n`;
		out += `\t}\n`;
		out += `}\n\n`;
	} else {
		out += `function C${i}() {\n`;
		out += `\t@render {\n`;
		out += `\t\t<div class="c">\n`;
		out += `\t\t\t${i}\n`;
		out += `\t\t\t<C${i + 1} />\n`;
		out += `\t\t</div>\n`;
		out += `\t}\n`;
		out += `}\n\n`;
	}
}

out += `export default function App() {\n`;
out += `\t@render {\n`;
out += `\t\t<C1 />\n`;
out += `\t}\n`;
out += `}\n`;

writeFileSync(resolve(HERE, 'src/App.torp'), out);
console.log('wrote src/App.torp');
