// Bundle-size gate for the view benchmark fixtures.
//
// Builds every fixture in production mode with esbuild minification (the same
// app for all five frameworks, so the numbers are directly comparable) and
// compares Torpor's JS payload against `size-baseline.json`.
//
// Usage:
//   pnpm size              # from benchmarks/view (or `pnpm --filter @torpor/benchmarks-view size`)
//   pnpm size:update       # rewrite the baseline after an intentional size change
//
// Requires a built @torpor/view: run `pnpm --filter @torpor/view build` first
// (or `pnpm build`).
//
// Only Torpor is gated: the other fixtures move with their framework versions
// and are printed for context. The gate is intentionally narrow (Torpor brotli
// size, >2% and >128 B growth fails) so it catches runtime regressions without
// tripping on minifier jitter.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { brotliCompressSync, constants, gzipSync } from 'node:zlib';
import { build } from 'vite';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '..', '..');
const BASELINE_FILE = path.join(HERE, 'size-baseline.json');
const VIEW_DIST = path.join(REPO_ROOT, 'packages', 'view', 'dist', 'index.mjs');

const FIXTURES = ['torpor', 'solid', 'svelte', 'vue', 'react'];
const MAX_GROWTH = 0.02;
const MIN_ALLOWANCE = 128; // bytes, so tiny jitter doesn't fail the gate

const UPDATE = process.argv.includes('--update');

async function buildFixture(name, outRoot) {
	const root = path.join(HERE, 'fixtures', name);
	const outDir = path.join(outRoot, name);

	await build({
		root,
		configFile: path.join(root, 'vite.config.js'),
		logLevel: 'error',
		build: {
			outDir,
			emptyOutDir: true,
			minify: 'esbuild',
			sourcemap: false,
			reportCompressedSize: false,
		},
	});

	return measure(path.join(outDir, 'assets'));
}

function measure(assetsDir) {
	let raw = 0;
	let gzip = 0;
	let brotli = 0;

	for (const file of fs.readdirSync(assetsDir)) {
		if (!file.endsWith('.js')) continue;
		const contents = fs.readFileSync(path.join(assetsDir, file));
		raw += contents.length;
		gzip += gzipSync(contents, { level: 9 }).length;
		brotli += brotliCompressSync(contents, {
			params: { [constants.BROTLI_PARAM_QUALITY]: 11 },
		}).length;
	}

	return { raw, gzip, brotli };
}

function format(kb) {
	return `${(kb / 1000).toFixed(1)} kB`;
}

function checkDist() {
	if (!fs.existsSync(VIEW_DIST)) {
		console.error(
			'Torpor dist not found. Build it first:\n' +
				'  pnpm --filter @torpor/view build',
		);
		process.exit(1);
	}

	const newestSource = newestSourceMtime(path.join(REPO_ROOT, 'packages', 'view', 'src'));
	if (newestSource > fs.statSync(VIEW_DIST).mtimeMs) {
		console.warn(
			'Warning: packages/view/dist is older than packages/view/src — the numbers below ' +
				'measure a stale build. Run `pnpm --filter @torpor/view build` first.\n',
		);
	}
}

function newestSourceMtime(dir) {
	let newest = 0;
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			newest = Math.max(newest, newestSourceMtime(full));
		} else if (entry.name.endsWith('.ts')) {
			newest = Math.max(newest, fs.statSync(full).mtimeMs);
		}
	}
	return newest;
}

checkDist();

const outRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'torpor-size-'));
const results = {};

try {
	for (const name of FIXTURES) {
		results[name] = await buildFixture(name, outRoot);
	}
} finally {
	fs.rmSync(outRoot, { recursive: true, force: true });
}

console.log('\nBundle size (same keyed 1000-row app, production, esbuild-minified):\n');
console.log('fixture    raw        gzip       brotli');
for (const name of FIXTURES) {
	const size = results[name];
	console.log(
		`${name.padEnd(10)} ${format(size.raw).padStart(9)} ${format(size.gzip).padStart(10)} ${format(
			size.brotli,
		).padStart(10)}`,
	);
}

const current = results.torpor;

if (UPDATE) {
	fs.writeFileSync(
		BASELINE_FILE,
		`${JSON.stringify({ note: 'Generated by size.mjs --update', torpor: current }, null, '\t')}\n`,
	);
	console.log(`\nBaseline updated: ${path.relative(REPO_ROOT, BASELINE_FILE)}`);
	process.exit(0);
}

const baseline = JSON.parse(fs.readFileSync(BASELINE_FILE, 'utf8')).torpor;
const delta = current.brotli - baseline.brotli;
const percent = (delta / baseline.brotli) * 100;
const limit = Math.max(MIN_ALLOWANCE, Math.round(baseline.brotli * MAX_GROWTH));

console.log(
	`\nTorpor brotli: ${format(current.brotli)} (baseline ${format(baseline.brotli)}, ` +
		`${delta >= 0 ? '+' : ''}${delta} B / ${percent >= 0 ? '+' : ''}${percent.toFixed(1)}%)`,
);

if (delta > limit) {
	console.error(
		`\nSize regression: Torpor grew by ${delta} B brotli ` +
			`(limit ${limit} B = max(${MIN_ALLOWANCE} B, ${MAX_GROWTH * 100}%)).\n` +
			'If the growth is intentional, update the baseline with `pnpm size:update`.',
	);
	process.exit(1);
}

console.log('Within budget.');
